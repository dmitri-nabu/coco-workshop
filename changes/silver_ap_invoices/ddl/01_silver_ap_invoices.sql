-- Onboard Baan + Workday into SILVER_AP_INVOICES (SRC-2025-003, SRC-2025-004).
-- Decisions: Q1 keep raw + normalized payment terms; Q2 keep company_code_raw/source_doc_type (NULL for new sources);
-- Workday branch included. Adds approval_status (BR-001) at the end of the column list.
CREATE OR ALTER DYNAMIC TABLE COCO_WORKSHOP.PIPELINE_LAB.SILVER_AP_INVOICES
  TARGET_LAG = '1 hour' REFRESH_MODE = AUTO INITIALIZE = ON_CREATE WAREHOUSE = COMPUTE_WH
AS
WITH unioned AS (
SELECT 'SAP' || '|' || INVOICE_ID AS invoice_key, 'SAP' AS source_system, INVOICE_ID AS source_invoice_id, INVOICE_NUMBER AS invoice_number,
  VENDOR_ID AS vendor_id, VENDOR_NAME AS vendor_name, INVOICE_DATE AS invoice_date, DUE_DATE AS due_date,
  INVOICE_AMOUNT::NUMBER(18,2) AS invoice_amount, UPPER(CURRENCY_CODE) AS currency_code,
  PAYMENT_TERMS AS payment_terms_raw,
  CASE UPPER(PAYMENT_TERMS) WHEN 'NET30' THEN 'NET30' WHEN 'NET60' THEN 'NET60' END AS payment_terms,
  CASE UPPER(PAYMENT_TERMS) WHEN 'NET30' THEN 30 WHEN 'NET60' THEN 60 END AS payment_terms_days,
  PO_NUMBER AS po_number, LINE_DESCRIPTION AS description, GL_ACCOUNT AS gl_account_raw, COST_CENTER AS cost_center_raw,
  APPROVAL_STATUS AS status_raw, CREATED_AT AS source_created_at, SAP_COMPANY_CODE AS company_code_raw,
  SAP_DOCUMENT_TYPE AS source_doc_type
FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_SAP_AP_INVOICES
UNION ALL
SELECT 'ORACLE' || '|' || INV_ID, 'ORACLE', INV_ID, INV_NUM, SUPPLIER_ID, SUPPLIER_NAME, INV_DATE, PAYMENT_DUE_DATE,
  TOTAL_AMOUNT::NUMBER(18,2), UPPER(CURRENCY), TERMS_CODE,
  CASE UPPER(TERMS_CODE) WHEN 'N30' THEN 'NET30' WHEN 'N60' THEN 'NET60' END,
  CASE UPPER(TERMS_CODE) WHEN 'N30' THEN 30 WHEN 'N60' THEN 60 END,
  PURCHASE_ORDER, DESCRIPTION, ACCOUNT_CODE, DEPT_CODE, STATUS, CREATION_DATE, ORACLE_ORG_ID, ORACLE_SOURCE
FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_ORACLE_AP_INVOICES
UNION ALL
SELECT 'BAAN' || '|' || BAN_INVOICE_ID, 'BAAN', BAN_INVOICE_ID, BAN_INVOICE_REF, BAN_VENDOR_CODE, BAN_VENDOR_DESC, BAN_INV_DATE, BAN_PAY_DATE,
  BAN_AMOUNT::NUMBER(18,2), UPPER(BAN_CURR), BAN_PAY_TERMS,
  CASE UPPER(BAN_PAY_TERMS) WHEN 'N30' THEN 'NET30' WHEN 'N60' THEN 'NET60' END,
  CASE UPPER(BAN_PAY_TERMS) WHEN 'N30' THEN 30 WHEN 'N60' THEN 60 END,
  BAN_PO_REF, BAN_LINE_DESC, BAN_GL_CODE, BAN_COST_CTR, BAN_STATUS, BAN_CREATED, NULL::VARCHAR, NULL::VARCHAR
FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_BAAN_AP_INVOICES
QUALIFY ROW_NUMBER() OVER (PARTITION BY BAN_INVOICE_REF ORDER BY BAN_CREATED DESC, BAN_INVOICE_ID DESC) = 1
UNION ALL
SELECT 'WORKDAY' || '|' || WD_INVOICE_ID, 'WORKDAY', WD_INVOICE_ID, WD_INVOICE_NUM, WD_SUPPLIER_ID, WD_SUPPLIER_NAME, WD_INVOICE_DATE, WD_DUE_DATE,
  WD_AMOUNT::NUMBER(18,2), UPPER(WD_CURRENCY), WD_PAY_TERMS,
  CASE UPPER(REPLACE(WD_PAY_TERMS,' ','')) WHEN 'NET30' THEN 'NET30' WHEN 'NET60' THEN 'NET60' END,
  CASE UPPER(REPLACE(WD_PAY_TERMS,' ','')) WHEN 'NET30' THEN 30 WHEN 'NET60' THEN 60 END,
  WD_PO_NUMBER, WD_MEMO, WD_LEDGER_ACCOUNT, WD_COST_CENTER, WD_APPROVAL_STATUS, WD_CREATED_DATE, NULL::VARCHAR, NULL::VARCHAR
FROM COCO_WORKSHOP.SOURCE_DATA.BRONZE_WORKDAY_AP_INVOICES
)
SELECT *,
  CASE UPPER(status_raw) WHEN 'APPROVED' THEN 'APPROVED' WHEN 'VALIDATED' THEN 'APPROVED' WHEN 'POSTED' THEN 'APPROVED'
                         WHEN 'PENDING' THEN 'PENDING' WHEN 'IN REVIEW' THEN 'PENDING' END AS approval_status
FROM unioned;
